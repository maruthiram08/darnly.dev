// Launch checker: reads one page plus a few files next to it (robots.txt, sitemap, favicon,
// a made-up address for the 404 check) and grades each launch basic green, amber or red.
// Every extra address goes through `probe`, which the Worker wires to the shared page reader,
// so the address checks, timeouts and read limits from index.ts apply here too.

export type Probe = { status: number; url: string; type: string; text: string };
export type Prober = (url: string, accept: string) => Promise<Probe | null>;

export type Level = 'pass' | 'warn' | 'fail';
export type Check = {
  id: string;
  label: string;
  level: Level;
  detail: string;
  fix?: string;
  prompt?: string;
  tool?: { href: string; name: string };
};

type Head = {
  title: string | null;
  meta: Record<string, string>;
  icons: { rel: string; href: string }[];
  images: number;
  noAlt: number;
  text: number;
  hidden: number;
  scripts: number;
};

// Titles and descriptions that starter templates ship with.
const STARTER = /^(vite \+ react( \+ ts)?|vite app|react app|create next app|generated by create next app|lovable generated project|lovable app|my v0 project|created with v0|bolt|astro|welcome to astro|nuxt|svelte ?kit app|my app|untitled|home|document)$/i;

const TOOLS = {
  og: { href: '/tools/open-graph-checker/', name: 'Open Graph checker' },
  meta: { href: '/tools/meta-tag-generator/', name: 'Meta tag generator' },
  favicon: { href: '/tools/favicon-generator/', name: 'Favicon generator' },
  sitemap: { href: '/tools/sitemap-generator/', name: 'Sitemap generator' },
};

export async function checkLaunch(html: string, pageUrl: string, probe: Prober, opts: { probeHttp: boolean }) {
  const page = new URL(pageUrl);
  const origin = page.origin;
  const head = await readHead(html, pageUrl);
  const missingPath = `/darnly-launch-check-${Math.random().toString(36).slice(2, 10)}`;

  const [robots, favicon, notFound, http] = await Promise.all([
    probe(`${origin}/robots.txt`, 'text/plain,*/*;q=0.1'),
    head.icons.length ? Promise.resolve(null) : probe(`${origin}/favicon.ico`, 'image/*,*/*;q=0.1'),
    probe(`${origin}${missingPath}`, 'text/html,*/*;q=0.1'),
    opts.probeHttp && page.protocol === 'https:' ? probe(`http://${page.host}${page.pathname}`, 'text/html,*/*;q=0.1') : Promise.resolve(null),
  ]);

  const robotsTxt = robots && isTextFile(robots) && robots.status === 200 ? robots.text : null;
  const sitemap = await findSitemap(origin, robotsTxt, probe);

  const checks: Check[] = [
    titleCheck(head),
    descriptionCheck(head),
    shareCheck(head),
    faviconCheck(head, favicon),
    httpsCheck(page, http),
    viewportCheck(head),
    indexCheck(head),
    robotsCheck(robots, robotsTxt),
    sitemapCheck(sitemap),
    notFoundCheck(notFound, origin, missingPath),
    altCheck(head),
  ];
  const js = jsCheck(head);
  if (js) checks.push(js);
  return { checks };
}

async function readHead(html: string, base: string): Promise<Head> {
  const h: Head = { title: null, meta: {}, icons: [], images: 0, noAlt: 0, text: 0, hidden: 0, scripts: 0 };
  let titleText = '';
  let inTitle = false;
  const abs = (v: string) => {
    try {
      return new URL(v, base).href;
    } catch {
      return v;
    }
  };
  const count = (s: string) => s.replace(/\s+/g, '').length;

  await new HTMLRewriter()
    .on('title', {
      element(el) {
        if (h.title !== null) return;
        inTitle = true;
        el.onEndTag(() => {
          inTitle = false;
          if (h.title === null) h.title = decode(titleText.trim());
        });
      },
      text(chunk) {
        if (inTitle && h.title === null) titleText += chunk.text;
      },
    })
    .on('meta', {
      element(el) {
        const key = (el.getAttribute('property') ?? el.getAttribute('name') ?? '').toLowerCase().trim();
        const content = el.getAttribute('content');
        if (key && content !== null && !(key in h.meta)) h.meta[key] = decode(content.trim());
      },
    })
    .on('link', {
      element(el) {
        const rel = (el.getAttribute('rel') ?? '').toLowerCase();
        const href = el.getAttribute('href');
        if (href && /\bicon\b/.test(rel)) h.icons.push({ rel, href: abs(href) });
      },
    })
    .on('img', {
      element(el) {
        h.images++;
        if (!el.hasAttribute('alt')) h.noAlt++;
      },
    })
    .on('body', { text: (c) => void (h.text += count(c.text)) })
    .on('body script', { text: (c) => void (h.hidden += count(c.text)) })
    .on('body style', { text: (c) => void (h.hidden += count(c.text)) })
    .on('body noscript', { text: (c) => void (h.hidden += count(c.text)) })
    .on('body template', { text: (c) => void (h.hidden += count(c.text)) })
    .on('script', { element: () => void h.scripts++ })
    .transform(new Response(html, { headers: { 'content-type': 'text/html' } }))
    .text();

  return h;
}

// --- Each check -------------------------------------------------------------------------

function titleCheck(h: Head): Check {
  const base = { id: 'title', label: 'Page title', tool: TOOLS.meta };
  const t = h.title;
  if (!t) return { ...base, level: 'fail', detail: 'Your page has no title, so Google and browser tabs have nothing to show.', fix: 'Add a <title> that says what the site is in under 60 characters.', prompt: 'My site has no page title. Add a <title> to every page that says what the page is in under 60 characters, for example "Product name: what it does".' };
  if (STARTER.test(t)) return { ...base, level: 'fail', detail: `Your title is still the starter text: “${t}”.`, fix: 'Replace it with your product’s name and what it does.', prompt: `My site’s page title is still the starter template text "${t}". Replace it with the product name and what it does, in under 60 characters, on every page.` };
  if (t.length > 60) return { ...base, level: 'warn', detail: `Your title is ${t.length} characters, so Google will cut it off around 60: “${t}”.`, fix: 'Shorten it to under 60 characters, with the important words first.', prompt: `My page title is ${t.length} characters long: "${t}". Shorten it to under 60 characters and keep the most important words first.` };
  if (t.length < 10) return { ...base, level: 'warn', detail: `Your title is very short: “${t}”. It doesn’t tell searchers what the site does.`, fix: 'Add a few words on what the site does.', prompt: `My page title is only "${t}". Make it say the product name and what it does, in 30 to 60 characters.` };
  return { ...base, level: 'pass', detail: `“${t}” (${t.length} characters).` };
}

function descriptionCheck(h: Head): Check {
  const base = { id: 'description', label: 'Description', tool: TOOLS.meta };
  const d = h.meta['description'];
  if (!d) return { ...base, level: 'fail', detail: 'There’s no description, so Google picks a random bit of your page to show under the title.', fix: 'Add a meta description of 120 to 160 characters.', prompt: 'My site has no meta description. Add <meta name="description"> to every page: one or two sentences, 120 to 160 characters, on what the page offers and who it’s for.' };
  if (STARTER.test(d)) return { ...base, level: 'fail', detail: `Your description is still the starter text: “${d}”.`, fix: 'Replace it with one or two sentences about your product.', prompt: `My meta description is still the starter template text "${d}". Replace it with 120 to 160 characters on what the product does and who it’s for.` };
  if (d.length > 160) return { ...base, level: 'warn', detail: `Your description is ${d.length} characters, so Google will cut it off around 160.`, fix: 'Trim it to under 160 characters.', prompt: `My meta description is ${d.length} characters. Trim it to under 160 characters and keep the main point at the start: "${d}"` };
  if (d.length < 50) return { ...base, level: 'warn', detail: `Your description is only ${d.length} characters: “${d}”.`, fix: 'Write one or two full sentences, 120 to 160 characters.', prompt: `My meta description is too short: "${d}". Rewrite it as 120 to 160 characters on what the product does and who it’s for.` };
  return { ...base, level: 'pass', detail: `${d.length} characters: “${d}”.` };
}

function shareCheck(h: Head): Check {
  const base = { id: 'share', label: 'Share preview', tool: TOOLS.og };
  const m = h.meta;
  const missing = ['og:title', 'og:description', 'og:image', 'twitter:card'].filter((k) => !m[k]);
  const image = m['og:image'] ?? m['og:image:url'];
  if (!image) return { ...base, level: 'fail', detail: missing.length === 4 ? 'Your page has no share tags, so links to it show up bare on X, LinkedIn, WhatsApp and Slack.' : `There’s no share picture (og:image), so links show up without one. Also missing: ${missing.filter((k) => k !== 'og:image').join(', ') || 'nothing else'}.`, fix: 'Add og:title, og:description, og:image (1200×630) and twitter:card.', prompt: `Add social share tags to my site so links look good on X, LinkedIn, WhatsApp and Slack: og:title, og:description, og:url, og:image (a 1200×630 picture with an absolute https URL), and twitter:card set to summary_large_image. Missing now: ${missing.join(', ')}.` };
  if (/lovable\.dev|opengraph-image-p98pqg|v0\.dev|vercel\.com\/og|bolt\.new/i.test(image)) return { ...base, level: 'warn', detail: 'Your share picture is still the default one from the tool that built the site.', fix: 'Make your own 1200×630 picture and point og:image at it.', prompt: `My og:image still points to the builder’s default picture (${image}). Create a 1200×630 share image for my product, save it in the site’s public folder, and point og:image and twitter:image at its absolute https URL.` };
  if (missing.length) return { ...base, level: 'warn', detail: `You have a share picture, but these tags are missing: ${missing.join(', ')}.`, fix: `Add ${missing.join(', ')}.`, prompt: `My site’s share tags are incomplete. Add ${missing.join(', ')}${missing.includes('twitter:card') ? ' (twitter:card should be summary_large_image)' : ''} to every page.` };
  return { ...base, level: 'pass', detail: 'Title, description, picture and X card are all set.' };
}

function faviconCheck(h: Head, ico: Probe | null): Check {
  const base = { id: 'favicon', label: 'Favicon', tool: TOOLS.favicon };
  const prompt = 'Add a full favicon set to my site: favicon.ico, a 32×32 PNG, a 180×180 apple-touch-icon, and the <link> tags for them in the page head.';
  if (h.icons.length) {
    if (h.icons.some((i) => /\/vite\.svg$|lovable|\/next\.svg$/i.test(i.href))) return { ...base, level: 'warn', detail: 'Your favicon is still the starter icon from the template.', fix: 'Swap in your own logo.', prompt: `My favicon is still the template’s default icon. Replace it with my own logo. ${prompt}` };
    if (!h.icons.some((i) => i.rel.includes('apple-touch-icon'))) return { ...base, level: 'warn', detail: 'You have a favicon, but no apple-touch-icon, so iPhones show a blurry screenshot when people save your site.', fix: 'Add a 180×180 apple-touch-icon.', prompt: 'Add a 180×180 PNG apple-touch-icon to my site and a <link rel="apple-touch-icon"> tag for it in the page head.' };
    return { ...base, level: 'pass', detail: 'Your page links a favicon and an apple-touch-icon.' };
  }
  if (ico && ico.status === 200 && !/html/.test(ico.type)) return { ...base, level: 'warn', detail: 'There’s a /favicon.ico, but your page doesn’t link any icons, so phones and some browsers show a blank one.', fix: 'Add <link rel="icon"> and apple-touch-icon tags.', prompt };
  return { ...base, level: 'fail', detail: 'No favicon found, so your tab shows a blank page icon.', fix: 'Make a favicon set from your logo and add the tags.', prompt };
}

function httpsCheck(page: URL, http: Probe | null): Check {
  const base = { id: 'https', label: 'HTTPS' };
  if (page.protocol !== 'https:') return { ...base, level: 'fail', detail: 'Your page loads over plain http, so browsers mark it “Not secure”.', fix: 'Turn on HTTPS at your host (Vercel, Netlify and Cloudflare do it for free).', prompt: 'My site is served over plain http. Tell me how to turn on HTTPS for it on my host, and make sure every http address redirects to https.' };
  if (http && http.status >= 200 && http.status < 300 && http.url.startsWith('http:')) return { ...base, level: 'warn', detail: 'The https version works, but the http:// address still shows the page instead of sending people to https.', fix: 'Turn on “Always use HTTPS” or add a redirect at your host.', prompt: 'My site still serves pages over http:// instead of redirecting to https://. Set up a permanent redirect from http to https on my host.' };
  return { ...base, level: 'pass', detail: 'Your site uses https.' };
}

function viewportCheck(h: Head): Check {
  const base = { id: 'viewport', label: 'Works on phones' };
  const v = h.meta['viewport'];
  const prompt = 'Add <meta name="viewport" content="width=device-width, initial-scale=1"> to the head of every page so my site fits phone screens.';
  if (!v) return { ...base, level: 'fail', detail: 'There’s no viewport tag, so phones show a tiny zoomed-out desktop page.', fix: 'Add <meta name="viewport" content="width=device-width, initial-scale=1">.', prompt };
  if (!/width\s*=\s*device-width/i.test(v)) return { ...base, level: 'warn', detail: `Your viewport tag doesn’t use the phone’s width: “${v}”.`, fix: 'Set it to width=device-width, initial-scale=1.', prompt };
  if (/user-scalable\s*=\s*(no|0)|maximum-scale\s*=\s*1(\.0)?\b/i.test(v)) return { ...base, level: 'warn', detail: 'Your viewport tag stops people zooming in, which makes text hard to read for some visitors.', fix: 'Remove user-scalable=no and maximum-scale=1.', prompt: `My viewport tag blocks zooming: "${v}". Change it to width=device-width, initial-scale=1 so people can zoom.` };
  return { ...base, level: 'pass', detail: 'Your page has a viewport tag for phones.' };
}

function indexCheck(h: Head): Check {
  const base = { id: 'index', label: 'Allowed in Google' };
  const r = `${h.meta['robots'] ?? ''} ${h.meta['googlebot'] ?? ''}`;
  if (/\bnoindex\b|\bnone\b/i.test(r)) return { ...base, level: 'fail', detail: 'Your page tells search engines not to list it (noindex). This is often left over from a staging site.', fix: 'Remove noindex from the robots meta tag.', prompt: `My page has <meta name="robots" content="${h.meta['robots'] ?? h.meta['googlebot']}">, which hides it from Google. Remove noindex from the production site, and keep it only on preview or staging builds if needed.` };
  return { ...base, level: 'pass', detail: 'Nothing on the page tells search engines to skip it.' };
}

function robotsCheck(res: Probe | null, txt: string | null): Check {
  const base = { id: 'robots', label: 'robots.txt', tool: TOOLS.sitemap };
  const prompt = 'Add a robots.txt at the root of my site that allows all crawlers and points to my sitemap:\n\nUser-agent: *\nAllow: /\n\nSitemap: https://<my domain>/sitemap.xml';
  if (txt === null) {
    const html = res && res.status === 200 && !isTextFile(res);
    return { ...base, level: 'warn', detail: html ? 'Asking for /robots.txt returns your web page instead of a robots file.' : 'There’s no /robots.txt. Search engines will still visit, but it’s the usual place to point them to your sitemap.', fix: 'Add a robots.txt that allows crawlers and links your sitemap.', prompt };
  }
  if (blocksAll(txt)) return { ...base, level: 'fail', detail: 'Your robots.txt blocks every search engine from the whole site (Disallow: /).', fix: 'Change Disallow: / to Allow: / for User-agent: *.', prompt: 'My robots.txt blocks all crawlers with "Disallow: /". Change it to allow all crawlers on the production site, and keep the sitemap line.' };
  return { ...base, level: 'pass', detail: 'Your robots.txt lets search engines in.' };
}

function sitemapCheck(s: { url: string; count: number } | null): Check {
  const base = { id: 'sitemap', label: 'Sitemap', tool: TOOLS.sitemap };
  if (!s) return { ...base, level: 'warn', detail: 'We couldn’t find a sitemap at /sitemap.xml or in robots.txt, so Google has to find your pages on its own.', fix: 'Generate a sitemap.xml and link it from robots.txt.', prompt: 'Generate a sitemap.xml for my site that lists every public page and updates on each build (use the usual sitemap plugin for this framework if there is one), and add a "Sitemap:" line for it to robots.txt.' };
  return { ...base, level: 'pass', detail: `Found ${s.url}${s.count ? ` with ${s.count} link${s.count === 1 ? '' : 's'}` : ''}.` };
}

function notFoundCheck(res: Probe | null, origin: string, path: string): Check {
  const base = { id: '404', label: 'Missing pages return 404' };
  const prompt = 'When someone visits an address that doesn’t exist on my site, it should show a friendly “page not found” page and return HTTP status 404, not 200. Set that up for my framework and host, including for single-page app routing.';
  if (!res) return { ...base, level: 'warn', detail: 'We couldn’t check what happens on a missing page.' };
  if (res.status === 404 || res.status === 410) return { ...base, level: 'pass', detail: 'A made-up address correctly answers “not found” (404).' };
  if (res.status >= 200 && res.status < 300) {
    const home = res.url.replace(/\/$/, '') === origin;
    return { ...base, level: home ? 'warn' : 'fail', detail: home ? 'A made-up address quietly sends people to your home page. Google can treat that as a broken page.' : `A made-up address (${path}) shows a normal page with status 200. Google may list junk addresses, and broken links look like they work.`, fix: 'Return a 404 status with a “page not found” page.', prompt };
  }
  return { ...base, level: 'warn', detail: `A made-up address answers with error ${res.status} instead of 404.`, fix: 'Return a 404 status with a “page not found” page.', prompt };
}

function altCheck(h: Head): Check {
  const base = { id: 'alt', label: 'Image alt text' };
  if (!h.images) return { ...base, level: 'pass', detail: 'There are no images in the page’s HTML to check.' };
  if (!h.noAlt) return { ...base, level: 'pass', detail: h.images === 1 ? 'The one image on the page has alt text.' : `All ${h.images} images have alt text.` };
  const prompt = `${h.noAlt} of the ${h.images} images on my page have no alt attribute. Add alt text to every <img>: a short description for images that carry meaning, and alt="" for decorative ones.`;
  const all = h.noAlt === h.images && h.images >= 3;
  return { ...base, level: all ? 'fail' : 'warn', detail: `${h.noAlt} of ${h.images} images have no alt text, so screen readers and Google can’t tell what they show.`, fix: 'Add a short alt description to each image (alt="" for decorative ones).', prompt };
}

// Only shown when it matters: pages that are an empty shell filled in by JavaScript.
function jsCheck(h: Head): Check | null {
  const visible = h.text - h.hidden;
  if (visible >= 150 || h.scripts === 0) return null;
  return {
    id: 'js',
    label: 'Readable without JavaScript',
    level: 'warn',
    detail: 'Your page’s HTML is nearly empty and gets filled in by JavaScript. Google copes, but share previews, AI crawlers and some search engines only read the HTML, so the title, description and share tags above are all they see.',
    fix: 'Put the title, description and share tags in the HTML, or prerender your pages.',
    prompt: 'My site is a single-page app whose HTML is almost empty until JavaScript runs. Make sure each page’s title, description and share tags are in the HTML that’s sent, and if this framework supports it, prerender or server-render the main pages so their text is in the HTML.',
  };
}

// --- Helpers ----------------------------------------------------------------------------

function isTextFile(p: Probe): boolean {
  return !/html/i.test(p.type) && !/^\s*</.test(p.text);
}

// True when the rules for every crawler (User-agent: *) include "Disallow: /".
function blocksAll(txt: string): boolean {
  let agents: string[] = [];
  let inRules = false;
  for (const raw of txt.split(/\r?\n/)) {
    const line = raw.replace(/#.*/, '').trim();
    const m = line.match(/^([a-z-]+)\s*:\s*(.*)$/i);
    if (!m) continue;
    const key = m[1].toLowerCase();
    const val = m[2].trim();
    if (key === 'user-agent') {
      if (inRules) agents = [];
      inRules = false;
      agents.push(val);
    } else {
      inRules = true;
      if (key === 'disallow' && val === '/' && agents.includes('*')) return true;
    }
  }
  return false;
}

async function findSitemap(origin: string, robots: string | null, probe: Prober) {
  const fromRobots = robots ? [...robots.matchAll(/^\s*sitemap\s*:\s*(\S+)/gim)].map((m) => m[1]) : [];
  const tries = [...new Set([...fromRobots.slice(0, 2), `${origin}/sitemap.xml`, `${origin}/sitemap-index.xml`])];
  for (const u of tries) {
    const res = await probe(u, 'application/xml,text/xml,*/*;q=0.1');
    if (res && res.status === 200 && /<(urlset|sitemapindex)[\s>]/i.test(res.text)) {
      return { url: res.url, count: (res.text.match(/<loc>/gi) ?? []).length };
    }
  }
  return null;
}

function decode(s: string): string {
  return s
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)))
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&');
}
